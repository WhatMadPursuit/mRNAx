"""Schema 3: Deterministic Audit, Scores & Action Transparency (`EvaluationReport`)."""

from __future__ import annotations

import json
from typing import Any, Literal, Self

from pydantic import Field, model_validator

from mrnax.schemas.common import ChemistryEvalMode, ComplianceProfile, ConstraintScope
from mrnax.schemas.construct_bundle import FrozenSchemaModel


def serialize_report_artifact(data: dict[str, Any]) -> bytes:
    """Serialize the evaluation_report.json artifact pinned by the pipeline receipt."""
    return (json.dumps(data, indent=2, sort_keys=True) + "\n").encode("utf-8")


class MetricResult(FrozenSchemaModel):
    metric_id: str = Field(min_length=1)
    value: float | None
    unit: str
    direction: Literal["maximize", "minimize", "target_band", "informational"]
    evaluated_scopes: list[ConstraintScope]
    tool_name: str
    tool_version: str
    chemistry_evaluation_mode: ChemistryEvalMode
    participated_in: Literal[
        "generation_guidance",
        "hard_filtering",
        "pareto_selection_or_ranking",
        "display_only",
    ]
    chain_values: list[float] | None = None
    notes: str | None = None

    @model_validator(mode="after")
    def _forbid_eternafold_mfe_conflation(self) -> Self:
        mid_low = self.metric_id.lower()
        unit_low = self.unit.lower()
        tool_low = self.tool_name.lower()
        is_prob_tool = "eternafold" in tool_low or "contrafold" in tool_low or "eternafold" in mid_low
        is_mfe_field = "mfe" in mid_low or "kcal" in mid_low or "kcal" in unit_low
        if is_prob_tool and is_mfe_field:
            raise ValueError(
                f"MetricResult '{self.metric_id}' (tool='{self.tool_name}', unit='{self.unit}') illegally conflates "
                "EternaFold/CONTRAfold pairing probabilities or dimensionless CRF scores with thermodynamic kcal/mol MFE"
            )
        if unit_low == "probability" and self.value is not None and not (0.0 <= float(self.value) <= 1.0):
            raise ValueError(
                f"MetricResult '{self.metric_id}' declares unit='probability' but value={self.value} is outside [0, 1]"
            )
        return self


class FTOAlert(FrozenSchemaModel):
    rule_id: str
    patent_family_or_pub: str
    matched_scope: ConstraintScope
    transcript_coordinates: tuple[int, int]
    identity_or_pattern: str
    blocked: bool
    summary: str
    bundle_id: str | None = None
    molecule_id: str | None = None
    paired_intervals: list[tuple[int, int]] | None = None


class AdvisoryNote(FrozenSchemaModel):
    advisory_id: str
    category: Literal[
        "cap_5prime_dinucleotide",
        "cytoplasmic_splice_motif",
        "utr3_canonical_pas",
        "cds_internal_pas",
        "crs_safety_layer_boundary",
        "chemistry_approximation",
        "model_domain_boundary",
    ]
    message: str
    transcript_coordinates: tuple[int, int] | None = None


class BundleEvaluation(FrozenSchemaModel):
    bundle_id: str
    version_digest: str
    passed_all_hard_gates: bool = True
    pareto_rank: int = Field(ge=1)
    metrics: list[MetricResult]
    selection_rationale: list[str] = Field(default_factory=list)


class FailedCandidateDiagnostic(FrozenSchemaModel):
    candidate_ref: str
    violated_requirement_id: str
    violated_scope: ConstraintScope
    transcript_coordinates: tuple[int, int]
    reason: str


class RequirementActionTrace(FrozenSchemaModel):
    """Deterministically generated by mrnax_core — NEVER free-written by LLM."""

    requirement_id: str
    stage_applied: Literal["generation", "filtering", "ranking", "recorded_only"]
    eliminated_count: int = Field(ge=0)
    changed_candidate_ids: list[str] = Field(default_factory=list)
    proof_diff_summary: str


class EvaluationReport(FrozenSchemaModel):
    report_id: str = Field(min_length=1)
    execution_id: str = Field(min_length=1)
    intent_id: str = Field(min_length=1)
    intent_version: int = Field(ge=1)
    compliance_track: ComplianceProfile
    outcome_status: Literal[
        "COMPLETED_WITH_CANDIDATES",
        "COMPLETED_ZERO_QUALIFIED",
        "COMPLETED_TIE",
        "UNCOMPARABLE_MISSING_APPROVED_COMPONENT",
    ]
    uncomparable_reason: str | None = None
    recommended_bundle_ids: list[str]
    candidate_evaluations: list[BundleEvaluation]
    failed_diagnostics: list[FailedCandidateDiagnostic]
    fto_alerts: list[FTOAlert]
    pre_synthesis_advisories: list[AdvisoryNote]
    action_transparency: list[RequirementActionTrace]
    created_at_ns: int | None = None
    rule_snapshot_version: str | None = None
    isolated_sandbox_override: bool = False

    @model_validator(mode="after")
    def _enforce_zero_qualified_and_uncomparable_rules(self) -> Self:
        if self.outcome_status in {
            "COMPLETED_ZERO_QUALIFIED",
            "UNCOMPARABLE_MISSING_APPROVED_COMPONENT",
        }:
            if self.recommended_bundle_ids:
                raise ValueError(
                    f"recommended_bundle_ids must be empty when outcome_status is {self.outcome_status}"
                )
            if self.candidate_evaluations:
                raise ValueError(
                    f"candidate_evaluations must be empty when outcome_status is {self.outcome_status}"
                )
        for ev in self.candidate_evaluations:
            if not ev.passed_all_hard_gates:
                raise ValueError(
                    f"Disqualified candidate '{ev.bundle_id}' cannot appear in candidate_evaluations; use failed_diagnostics"
                )
        qualified_ids = {ev.bundle_id for ev in self.candidate_evaluations}
        unknown_recs = [bid for bid in self.recommended_bundle_ids if bid not in qualified_ids]
        if unknown_recs:
            raise ValueError(
                f"recommended_bundle_ids {unknown_recs} must reference qualified candidate_evaluations"
            )
        return self
